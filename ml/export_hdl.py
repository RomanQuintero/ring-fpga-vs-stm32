import numpy as np
from pathlib import Path

INPUT = Path("pong_mlp_int8.npz")
OUTPUT = Path("pong_weights.svh")

d = np.load(INPUT)

W1 = d["W1"].astype(np.int8)      # (5, 16)
B1 = d["B1"].astype(np.int32)     # (16,)
W2 = d["W2"].astype(np.int8)      # (16, 3)
B2 = d["B2"].astype(np.int32)     # (3,)

assert W1.shape == (5, 16)
assert B1.shape == (16,)
assert W2.shape == (16, 3)
assert B2.shape == (3,)

def sv8(value):
    value = int(value)
    return f"8'sd{value}" if value >= 0 else f"-8'sd{abs(value)}"

def sv32(value):
    value = int(value)
    return f"32'sd{value}" if value >= 0 else f"-32'sd{abs(value)}"

lines = []

lines.append("// AUTO-GENERATED by export_hdl.py")
lines.append("// RING neural controller")
lines.append("// Architecture: 5 -> 16 -> 3")
lines.append("// Weights: signed INT8")
lines.append("// Biases: signed INT32")
lines.append("")

# W1 is stored by sklearn as [input][neuron]
lines.append("localparam logic signed [7:0] W1 [0:4][0:15] = '{")
for i in range(5):
    row = ", ".join(sv8(v) for v in W1[i])
    comma = "," if i < 4 else ""
    lines.append(f"    '{{{row}}}{comma}")
lines.append("};")
lines.append("")

lines.append("localparam logic signed [31:0] B1 [0:15] = '{")
lines.append("    " + ", ".join(sv32(v) for v in B1))
lines.append("};")
lines.append("")

lines.append("localparam logic signed [7:0] W2 [0:15][0:2] = '{")
for i in range(16):
    row = ", ".join(sv8(v) for v in W2[i])
    comma = "," if i < 15 else ""
    lines.append(f"    '{{{row}}}{comma}")
lines.append("};")
lines.append("")

lines.append("localparam logic signed [31:0] B2 [0:2] = '{")
lines.append("    " + ", ".join(sv32(v) for v in B2))
lines.append("};")
lines.append("")

OUTPUT.write_text("\n".join(lines), encoding="utf-8")

print(f"Generated: {OUTPUT}")
print(f"W1: {W1.shape}  B1: {B1.shape}")
print(f"W2: {W2.shape} B2: {B2.shape}")
print("Architecture: 5 -> 16 -> 3")
print("Total weights:", W1.size + W2.size)